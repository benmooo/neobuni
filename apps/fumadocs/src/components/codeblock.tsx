"use client";
import { useTranslations } from "@fuma-translate/react";
import { useCopyButton } from "@fumadocs/base-ui/utils/use-copy-button";
import { Check, Clipboard } from "lucide-react";
import {
  type ComponentProps,
  createContext,
  type HTMLAttributes,
  type ReactNode,
  type RefObject,
  use,
  useMemo,
  useRef,
} from "react";

import { cn } from "../lib/cn";
import { mergeRefs } from "../lib/merge-refs";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "./tabs/ui";
import { buttonVariants } from "./ui/button";

export interface CodeBlockProps
  extends Omit<ComponentProps<"figure">, "title"> {
  Actions?: (props: { className?: string; children?: ReactNode }) => ReactNode;

  /**
   * Allow to copy code with copy button
   *
   * @defaultValue true
   */
  allowCopy?: boolean | "true" | "false";

  /**
   * show line numbers
   */
  "data-line-numbers"?: boolean;

  /**
   * @defaultValue 1
   */
  "data-line-numbers-start"?: number;

  /**
   * Icon of code block
   *
   * When passed as a string, it assumes the value is the HTML of icon
   */
  icon?: ReactNode;

  /**
   * Keep original background color generated by Shiki or Rehype Code
   *
   * @defaultValue false
   */
  keepBackground?: boolean;
  title?: ReactNode;

  viewportProps?: HTMLAttributes<HTMLElement>;
}

const TabsContext = createContext<{
  containerRef: RefObject<HTMLDivElement | null>;
  nested: boolean;
} | null>(null);

export function Pre(props: ComponentProps<"pre">) {
  return (
    <pre
      {...props}
      className={cn("w-max min-w-full *:flex *:flex-col", props.className)}
    >
      {props.children}
    </pre>
  );
}

export function CodeBlock({
  ref,
  title,
  allowCopy = true,
  keepBackground = false,
  icon,
  viewportProps = {},
  children,
  Actions = (props) => (
    <div {...props} className={cn("empty:hidden", props.className)} />
  ),
  ...props
}: CodeBlockProps) {
  const inTab = use(TabsContext) !== null;
  const areaRef = useRef<HTMLDivElement>(null);
  if (allowCopy === "true") {
    allowCopy = true;
  } else if (allowCopy === "false") {
    allowCopy = false;
  }
  return (
    <figure
      dir="ltr"
      ref={ref}
      {...props}
      className={cn(
        inTab
          ? "-mx-px -mb-px bg-fd-secondary last:rounded-b-xl"
          : "my-4 rounded-xl bg-fd-card",
        keepBackground && "bg-(--shiki-light-bg) dark:bg-(--shiki-dark-bg)",

        "shiki not-prose relative overflow-hidden border text-sm",
        props.className
      )}
      tabIndex={-1}
    >
      {title ? (
        <div className="flex h-9.5 items-center gap-2 border-b px-4 text-fd-muted-foreground">
          {typeof icon === "string" ? (
            <div
              className="[&_svg]:size-3.5"
              dangerouslySetInnerHTML={{
                __html: icon,
              }}
            />
          ) : (
            icon
          )}
          <figcaption className="flex-1 truncate">{title}</figcaption>
          {Actions({
            className: "-me-2",
            children: allowCopy && <CopyButton containerRef={areaRef} />,
          })}
        </div>
      ) : (
        Actions({
          className:
            "absolute top-2 right-2 z-2 backdrop-blur-lg rounded-lg text-fd-muted-foreground",
          children: allowCopy && <CopyButton containerRef={areaRef} />,
        })
      )}
      <div
        ref={areaRef}
        {...viewportProps}
        className={cn(
          "fd-scroll-container max-h-[600px] overflow-auto py-3.5 text-[0.8125rem] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-fd-ring focus-visible:ring-inset",
          viewportProps.className
        )}
        role="region"
        style={
          {
            // space for toolbar
            "--padding-right": title ? undefined : "calc(var(--spacing) * 8)",
            counterSet: props["data-line-numbers"]
              ? `line ${Number(props["data-line-numbers-start"] ?? 1) - 1}`
              : undefined,
            ...viewportProps.style,
          } as React.CSSProperties
        }
      >
        {children}
      </div>
    </figure>
  );
}

function CopyButton({
  className,
  containerRef,
  ...props
}: ComponentProps<"button"> & {
  containerRef: RefObject<HTMLElement | null>;
}) {
  const t = useTranslations({ note: "code block" });
  const [checked, onClick] = useCopyButton(() => {
    const pre = containerRef.current?.getElementsByTagName("pre").item(0);
    if (!pre) {
      return;
    }

    const clone = pre.cloneNode(true) as HTMLElement;
    clone.querySelectorAll(".nd-copy-ignore").forEach((node) => {
      node.replaceWith("\n");
    });

    return navigator.clipboard.writeText(clone.textContent ?? "");
  });

  return (
    <button
      aria-live="polite"
      className={cn(
        buttonVariants({
          className:
            "hover:text-fd-accent-foreground data-checked:text-fd-accent-foreground",
          size: "icon-xs",
        }),
        className
      )}
      data-checked={checked || undefined}
      onClick={onClick}
      type="button"
      {...props}
    >
      {checked ? <Check /> : <Clipboard />}
      <span className="sr-only">
        {checked
          ? t("Copied Text", { note: "aria-label" })
          : t("Copy Text", { note: "aria-label" })}
      </span>
    </button>
  );
}

export function CodeBlockTabs({
  ref,
  className,
  ...props
}: ComponentProps<typeof Tabs>) {
  const containerRef = useRef<HTMLDivElement>(null);
  const nested = use(TabsContext) !== null;

  return (
    <Tabs
      ref={mergeRefs(containerRef, ref)}
      {...props}
      className={(s) =>
        cn(
          "rounded-xl border bg-fd-card",
          !nested && "my-4",
          typeof className === "function" ? className(s) : className
        )
      }
    >
      <TabsContext
        value={useMemo(
          () => ({
            containerRef,
            nested,
          }),
          [nested]
        )}
      >
        {props.children}
      </TabsContext>
    </Tabs>
  );
}

export function CodeBlockTabsList({
  className,
  ...props
}: ComponentProps<typeof TabsList>) {
  return (
    <TabsList
      {...props}
      className={(s) =>
        cn(
          "flex flex-row overflow-x-auto px-2 text-fd-muted-foreground",
          typeof className === "function" ? className(s) : className
        )
      }
    >
      {props.children}
    </TabsList>
  );
}

export function CodeBlockTabsTrigger({
  children,
  className,
  ...props
}: ComponentProps<typeof TabsTrigger>) {
  return (
    <TabsTrigger
      {...props}
      className={(s) =>
        cn(
          "group relative inline-flex items-center gap-2 text-nowrap px-2 py-1.5 font-medium text-sm transition-colors [&_svg]:size-3.5",
          s.active ? "text-fd-primary" : "hover:text-fd-accent-foreground",
          typeof className === "function" ? className(s) : className
        )
      }
    >
      <div className="absolute inset-x-2 bottom-0 h-px group-data-active:bg-fd-primary" />
      {children}
    </TabsTrigger>
  );
}

export function CodeBlockTab(props: ComponentProps<typeof TabsContent>) {
  return <TabsContent {...props} />;
}
